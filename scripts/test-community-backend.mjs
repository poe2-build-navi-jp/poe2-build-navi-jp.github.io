import assert from 'node:assert/strict';
import {readFile} from 'node:fs/promises';
import {stripTypeScriptTypes} from 'node:module';
import {tables, fault} from './fixtures/community-db-sdk.mjs';
const root = new URL('../', import.meta.url);
const catalog = JSON.parse(await readFile(new URL('data/community-catalog.json', root)));
const samples = JSON.parse(await readFile(new URL('tools/community-service/src/samples.json', root)));
let source = await readFile(new URL('tools/community-service/backend/index.ts', root), 'utf8');
source = source.replace("from '@appdeploy/sdk'", "from '" + new URL('./fixtures/community-db-sdk.mjs', import.meta.url).href + "'")
  .replace("from '../src/community-model.js'", "from '" + new URL('assets/community-model.js', root).href + "'")
  .replace("import catalog from '../src/catalog.json';", 'const catalog = ' + JSON.stringify(catalog) + ';');
const {handler} = await import('data:text/javascript;base64,' + Buffer.from(stripTypeScriptTypes(source)).toString('base64'));
const call = async (operation, body) => {
  const result = await handler({operation, body});
  return {status: result.statusCode, data: JSON.parse(result.body)};
};
const token = 'A'.repeat(43), id = 'community-qa-post-00000001';
const post = {version: 1, title: 'QA Twister', nickname: 'QA', description: 'Public only', purpose: 'boss', budget: {amount: 4, currency: 'divine'}, snapshot: samples[0].saved};
const input = {id, token, consent: true, post};
assert.equal((await call('publish', {...input, consent: false})).status, 400);
assert.equal((await call('publish', {...input, token: undefined})).status, 400);
assert.equal((await call('publish', input)).status, 201);
assert.equal((await call('publish', input)).status, 200, 'exact retry returns durable receipt');
assert.equal((await call('publish', {...input, post: {...post, title: 'Changed'}})).status, 409);
assert.equal((await call('publish', {...input, token: 'B'.repeat(43)})).status, 403);
const read = await call('read', {id});
assert.equal(read.data.title, post.title);
assert(!JSON.stringify(read).includes(token));
assert(!('owner' in read.data) && !('digest' in read.data));
assert.equal((await call('list', {filters: {maximum: 5, currency: 'divine', purpose: 'boss', skill: 'TwisterPlayer'}})).data.posts.length, 1);
assert.equal((await call('list', {filters: {maximum: 5, currency: 'chaos'}})).data.posts.length, 0);
assert.equal((await call('mine', {token})).data.posts.length, 1);
assert.equal((await call('mine', {token: 'B'.repeat(43)})).data.posts.length, 0);
assert.equal((await call('withdraw', {id, token: 'B'.repeat(43)})).status, 403);
assert.equal((await call('read', {id})).status, 200);
const report = {id, reporter: 'C'.repeat(43), reason: 'other', note: 'QA report'};
assert.equal((await call('report', report)).data.received, true);
assert.equal((await call('report', report)).data.received, true);
assert.equal(tables.get('poe2_public_reports').size, 1);
fault.before = 'AppDatabaseConditionFailed';
assert.equal((await call('publish', {...input, id: 'community-qa-post-00000002'})).status, 201, 'known-aborted conflict retries with fresh handles');
fault.after = 'AppDatabaseUnknownOutcome';
assert.equal((await call('publish', {...input, id: 'community-qa-post-00000003'})).status, 200, 'unknown commit reconciles without a second effect');
assert.equal((await call('mine', {token})).data.posts.length, 3);
fault.before = 'AppDatabaseQuotaExceeded';
assert.equal((await call('publish', {...input, id: 'community-qa-post-00000004'})).status, 429);
assert.equal((await call('mine', {token})).data.posts.length, 3);
fault.after = 'AppDatabaseUnknownOutcome';
assert.equal((await call('withdraw', {id, token})).data.withdrawn, true);
assert.equal((await call('withdraw', {id, token})).data.withdrawn, true);
assert.equal((await call('read', {id})).status, 404);
assert.equal((await call('publish', input)).status, 409, 'a replay cannot resurrect a withdrawn snapshot');
assert.equal((await call('mine', {token})).data.posts.length, 2);
assert(!tables.get('poe2_public_posts').get(id).data, 'withdrawal removes the live public snapshot');
assert(!(await call('list', {})).data.posts.some(post => post.id === id));
for (let number = 4; number <= 11; number++) assert.equal((await call('publish', {...input, id: 'community-qa-post-' + String(number).padStart(8, '0')})).status, 201);
assert.equal((await call('publish', {...input, id: 'community-qa-post-00000012'})).status, 429);
assert.equal((await call('list', {filters: {skill: 'MadeUp'}})).status, 400);
console.log('PASS: durable publishing, bounded public filters, private owner boundaries, consent, idempotent reports, atomic withdrawal, CAS/replay reconciliation and limits');
