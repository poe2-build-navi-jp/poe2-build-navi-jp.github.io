import assert from 'node:assert/strict';
import {readFile} from 'node:fs/promises';
import {makeGoal, parseGoal, compareGoal, goalKey, itemFingerprint} from '../assets/simulator-goal-model.js';

const data = JSON.parse(await readFile(new URL('../data/simulator-examples.json', import.meta.url)));
const original = data.examples.find(example => example.id === 'complete-mercenary-twister-gemling').saved;
const saved = () => structuredClone(original);
const candidate = value => ({kind: 'plan', id: 'target-test', name: '目標 <img src=x onerror=alert(1)>', saved: value});
const item = (slot, modifier, name = 'An item') => ({slot, text: `Rarity: RARE\n${name}\nAmethyst Ring\nItem Level: 80\nImplicits: 0\n+${modifier} to maximum Life`});
const nodeInfo = id => id === 999999 ? null : {name: 'Node ' + id, kind: 'normal', attribute: id === 3};
const options = {nodeInfo, starts: [1], gemInfo: id => ({support: id.startsWith('Support')})};

const source = saved(); source.notes = 'PRIVATE NOTES';
const before = JSON.stringify(source), goal = makeGoal(candidate(source), source.preset);
assert.equal(JSON.stringify(source), before);
assert.equal(goal.saved.notes, '');
assert.equal(parseGoal(JSON.stringify(goal), source.preset).name, goal.name);
source.request.character.level = 1;
assert.equal(goal.saved.request.character.level, 100, 'the target is a frozen snapshot');
assert(!goalKey(source.preset).startsWith('poe2-simulator:'), 'goal preferences stay separate from named-save sync and backups');

let target = saved(), current = saved();
target.request.socket_groups = [{enabled: true, gems: [{skill_id: 'Main', level: 20, quality: 20}, {skill_id: 'SupportA', level: 1, quality: 0}]}];
current.request.socket_groups = [{enabled: true, gems: [{skill_id: 'Main', level: 21, quality: 10}]}, {enabled: true, gems: [{skill_id: 'Other', level: 1}, {skill_id: 'SupportA', level: 1}]}];
let result = compareGoal(current, makeGoal(candidate(target), target.preset), options);
assert.equal(result.gems.missing, 1, 'a support in a different active skill does not satisfy the target');
assert.equal(result.gems.upgrades, 1, 'quality below target is reported separately');
current.request.socket_groups[0].gems[0].quality = 21;
current.request.socket_groups[0].gems.push({skill_id: 'SupportA', level: 2, quality: 0});
result = compareGoal(current, makeGoal(candidate(target), target.preset), options);
assert.equal(result.gems.missing + result.gems.upgrades, 0);
current.request.socket_groups[0].main_active_skill = 2;
assert(compareGoal(current, makeGoal(candidate(target), target.preset), options).gems.mainDifferent, 'a different active skill selection remains a configuration gap');
current.request.socket_groups[0].main_active_skill = 1;
current.request.socket_groups[0].enabled = false;
assert.equal(compareGoal(current, makeGoal(candidate(target), target.preset), options).gems.missing, 2, 'disabled gems/groups are not treated as configured');
target.request.socket_groups[0].gems.push({skill_id: 'SupportA', level: 1, quality: 0});
current.request.socket_groups[0].enabled = true;
assert.equal(compareGoal(current, makeGoal(candidate(target), target.preset), options).gems.missing, 1, 'duplicate requirements consume separate gem entries');

target = saved(); current = saved();
target.request.allocated_nodes = [1, 2, 3, 999999];
current.request.allocated_nodes = [1, 3];
current.request.attribute_choices = {'3': 'dex'};
result = compareGoal(current, makeGoal(candidate(target), target.preset), options);
assert.equal(result.passives.missing, 1);
assert.equal(result.passives.choices, 1);
assert.equal(result.passives.unknown, 1);
assert(!result.passives.rows.some(row => row.id === 1), 'class starts do not count as missing points');
target.request.tree_version = 'different_tree';
assert.equal(compareGoal(current, makeGoal(candidate(target), target.preset), options).passives.available, false);
delete target.request.tree_version;
target.request.allocated_nodes = [1, 2, 5];
target.request.weapon_swap = {active: 1, exclusive_nodes: [[5], [6]]};
current.request.allocated_nodes = [1, 2, 6];
current.request.weapon_swap = {active: 1, exclusive_nodes: [[6], [5]]};
result = compareGoal(current, makeGoal(candidate(target), target.preset), options);
assert.equal(result.passives.missing, 2, 'nodes allocated to the wrong weapon set remain missing');

target = saved(); current = saved();
target.request.items = [item('ring1', 50), item('ring2', 70)]; target.weaponSets = null;
current.request.items = [item('ring1', 70, 'Other name'), item('ring2', 50, 'New name')]; current.weaponSets = null;
const targetText = JSON.stringify(target), currentText = JSON.stringify(current);
assert.equal(compareGoal(current, makeGoal(candidate(target), target.preset), options).equipment.pending, 0, 'equivalent rings may swap slots and have different rare names');
assert.equal(JSON.stringify(current), currentText, 'checking a goal does not mutate the current build');
current.request.items[1] = item('ring2', 60);
assert.equal(compareGoal(current, makeGoal(candidate(target), target.preset), options).equipment.pending, 1, 'exact ring matches are reserved before unmatched slots');
assert.equal(JSON.stringify(target), targetText);
assert.equal(itemFingerprint(item('ring1', 50).text), itemFingerprint(item('ring1', 50, 'A different name').text));

target = saved(); current = saved();
target.weaponSets.sets[1].items = [item('weapon1', 50)];
current.weaponSets.sets[1].items = [item('weapon1', 30)];
result = compareGoal(current, makeGoal(candidate(target), target.preset), options);
assert.equal(result.equipment.pending, 1, 'inactive weapon equipment is included');
assert.equal(result.equipment.rows.find(row => row.status === 'different').scope, 2);
current.request.character.class_name = 'Ranger';
assert.throws(() => compareGoal(current, makeGoal(candidate(target), target.preset), options), /GOAL_CLASS/);
assert.throws(() => parseGoal(JSON.stringify(goal), 'wrong-preset'));
const malformed = saved(); malformed.request.items = [{slot: 'helmet', text: {html: 'bad'}}];
assert.throws(() => makeGoal(candidate(malformed), malformed.preset));
assert.equal(JSON.stringify(data.examples.find(example => example.id === 'complete-mercenary-twister-gemling').saved), JSON.stringify(original));
console.log('PASS: immutable goal snapshots, grouped/disabled/duplicate gems, level and quality thresholds, passive version/attribute/weapon-set checks, class-start exclusions, unknown IDs, equivalent rings, inactive equipment and input validation');
