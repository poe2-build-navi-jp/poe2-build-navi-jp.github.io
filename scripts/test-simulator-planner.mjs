import assert from 'node:assert/strict';
import {readFile} from 'node:fs/promises';
import {plannerExport, validatePlanner, plannerSourceKey} from '../assets/simulator-planner-model.js';
const index = JSON.parse(await readFile(new URL('../data/simulator-index.json', import.meta.url)));
const examples = JSON.parse(await readFile(new URL('../data/simulator-examples.json', import.meta.url)));
const saved = structuredClone(examples.examples.find(example => example.id === 'complete-mercenary-twister-gemling').saved);
saved.notes = 'PRIVATE NOTE NEVER EXPORT';
const before = JSON.stringify(saved);
const result = plannerExport(saved, index, {name: '自分の目標', from: 80, to: 100});
assert.equal(result.omissions.length, 0);
assert.equal(result.counts.skills, 1); assert.equal(result.counts.supports, 3);
assert.equal(result.build.ascendancy, 'Mercenary3');
assert.equal(result.build.skills[0].id, 'Metadata/Items/Gem/SkillGemTwister');
assert(result.build.passives.every(node => typeof node.id === 'string' && !/^\d+$/.test(node.id)), 'official passive slugs are required, numeric simulator IDs are not planner IDs');
assert(result.build.passives.every(node => node.level_interval.join() === '80,100'));
assert.equal(JSON.stringify(saved), before, 'export never edits the source');
assert(!JSON.stringify(result.build).includes(saved.notes));
assert(!Object.hasOwn(result.build, 'items'));
assert.equal(validatePlanner(JSON.parse(JSON.stringify(result.build)), index).name, '自分の目標');
const scopeNode = saved.request.allocated_nodes.find(id => index.nodes[id]?.kind === 'normal');
saved.request.weapon_swap = {active: 1, exclusive_nodes: [[scopeNode], []]};
assert(plannerExport(saved, index, {name: 'scope'}).build.passives.some(node => node.id === index.nodes[scopeNode].id && node.weapon_set === 1));
saved.request.tree_version = '0_4';
const old = plannerExport(saved, index, {name: 'old'});
assert.equal(old.counts.passives, 0); assert(old.omissions.some(entry => entry.reason === 'tree-version'));
saved.request.socket_groups[0].gems.push({skill_id: 'UNKNOWN_SKILL', level: 1, quality: 0});
assert.throws(() => plannerExport(saved, index, {name: 'empty', passives: false}), /PLANNER_EMPTY/);
assert.throws(() => plannerExport(saved, index, {name: 'bad', from: 100, to: 1}), /PLANNER_LEVEL/);
const changedNotes = {...JSON.parse(before), notes: 'different note'};
assert.equal(plannerSourceKey(JSON.parse(before)), plannerSourceKey(changedNotes), 'private notes are not export inputs');
console.log('PASS: official planner field types and ID mappings, group supports, ascendancy, level intervals, weapon sets, unknown-ID omissions and unchanged private source');
