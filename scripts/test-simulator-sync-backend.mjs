import assert from 'node:assert/strict';
import {readFile} from 'node:fs/promises';
import {stripTypeScriptTypes} from 'node:module';
import {tables,fault} from './fixtures/sync-db-sdk.mjs';
const source=(await readFile(new URL('../tools/sync-service/backend/index.ts',import.meta.url),'utf8'))
  .replace("from '@appdeploy/sdk'",`from '${new URL('./fixtures/sync-db-sdk.mjs',import.meta.url).href}'`);
const {handler}=await import('data:text/javascript;base64,'+Buffer.from(stripTypeScriptTypes(source)).toString('base64'));
const auth={room:'r'.repeat(43),token:'t'.repeat(43)};
const call=async(operation,body=auth)=>{const result=await handler({operation,body});return {status:result.statusCode,data:JSON.parse(result.body)};};
assert.equal((await call('create')).status,200);
assert.equal((await call('create')).status,200);
assert.equal((await call('create',{...auth,token:'x'.repeat(43)})).status,403);
assert.equal((await call('read',{...auth,token:'x'.repeat(43)})).status,403);
assert.equal((await call('read',{room:'bad',token:'bad'})).status,400);
const first={...auth,revision:0,requestId:'first-request-0001',iv:'i'.repeat(16),ciphertext:'C'.repeat(300001)};
assert.equal((await call('write',first)).data.revision,1);
assert.equal((await call('write',first)).data.revision,1,'same request is idempotent');
assert.equal((await call('write',{...first,ciphertext:'D'.repeat(40)})).status,409,'request IDs cannot change payloads');
assert.equal((await call('write',{...first,requestId:'stale-request-0002'})).status,409);
const read=await call('read');assert.equal(read.data.envelope.ciphertext,first.ciphertext,'all durable chunks are read in order');
assert((await call('read',{...auth,revision:1})).data.unchanged);
fault.after='AppDatabaseUnknownOutcome';
const second={...first,revision:1,requestId:'second-request-0002',ciphertext:'S'.repeat(64)};
assert.equal((await call('write',second)).data.revision,2,'uncertain commit reconciles its atomic receipt');
assert.equal((await call('write',second)).data.revision,2);
fault.before='AppDatabaseConditionFailed';
assert.equal((await call('write',{...second,revision:2,requestId:'race-request-00003'})).status,409);
assert.equal((await call('read')).data.revision,2,'CAS failure changes neither metadata nor encrypted data');
fault.before='AppDatabaseQuotaExceeded';
assert.equal((await call('write',{...second,revision:2,requestId:'quota-request-0003'})).status,429);
assert.equal((await call('read')).data.revision,2);
assert.equal((await call('write',{...second,revision:2,requestId:'oversized-request-03',ciphertext:'A'.repeat(2800001)})).status,400);
assert.equal((await call('revoke')).data.revoked,true);
assert.equal(tables.get('poe2_vault_chunks').size,0,'revocation removes both bounded chunk banks');
assert.equal((await call('read')).status,403);
assert.equal((await call('write',{...second,revision:3,requestId:'revoked-request-003'})).status,403);
assert.equal((await call('revoke')).data.revoked,true,'revocation can be retried safely');
console.log('PASS: backend authorization, chunk persistence, conditional transactions, idempotency receipts, unknown-outcome reconciliation, usage limits and revocation');
