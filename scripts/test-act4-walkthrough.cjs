const assert=require('node:assert/strict');
const fs=require('node:fs');const path=require('node:path');const {JSDOM}=require('jsdom');
const root=path.resolve(__dirname,'..');const read=p=>fs.readFileSync(path.join(root,p),'utf8');
const data=JSON.parse(read('data/strategy-guides.json'));
const guide=data.find(g=>g.slug==='act-4-walkthrough');assert(guide,'Act4 article source data');
const article=new JSDOM(read('guides/act-4-walkthrough/index.html')).window.document;
const act3=new JSDOM(read('guides/act-3-walkthrough/index.html')).window.document;
const hub=new JSDOM(read('guides/index.html')).window.document;
const intent=JSON.parse(read('data/guide-search-intents.json')).find(g=>g.slug==='act-4-walkthrough');
assert(intent,'Distinct Act4 search intent');assert.equal(article.querySelector('h1').textContent,intent.h1);
assert(guide.sections.length>=8,'Substantive route, bosses, optional rewards and completion coverage');
assert(guide.sources.length>=5,'Explicit sources');assert(guide.faq.length>=3);
assert.equal(article.querySelectorAll('.content-action li').length,3);
assert(article.querySelector('.guide-toc details')||article.querySelector('details.guide-toc'));
assert(article.querySelector('a[href="/guides/act-3-walkthrough/"]'),'Act4 to Act3');
assert(act3.querySelector('a[href="/guides/act-4-walkthrough/"]'),'Act3 to Act4');
assert(hub.querySelector('.guide-featured a[href="/guides/act-4-walkthrough/"]'),'Compact featured route');
assert(hub.querySelector('#campaign a[data-guide-card][href="/guides/act-4-walkthrough/"]'),'Campaign card');
assert(article.querySelector('a[href="/guides/"]'),'Return to hub');
assert.equal(article.querySelector('link[rel=canonical]').href,'https://poe2-build-navi-jp.github.io/guides/act-4-walkthrough/');
assert(read('sitemap.xml').includes('/guides/act-4-walkthrough/</loc>'));
assert(!read('sitemap.xml').includes('/tests/'));
const qa=new JSDOM(read('tests/mobile.html')).window.document;assert.equal(qa.querySelector('meta[name=robots]').content,'noindex,nofollow');
console.log('PASS: Act4 content depth, distinct search intent, Act3↔Act4 and hub navigation, canonical, sitemap and QA noindex');
